export function getToolsByCategory(category: ToolCategory): TradingTool[] {
  return TRADING_TOOLS.filter((tool) => tool.category === category);
}

export function getToolById(id: string): TradingTool | undefined {
  return TRADING_TOOLS.find((tool) => tool.id === id);
}

export function searchTools(query: string): TradingTool[] {
  const lowerQuery = query.toLowerCase();
  return TRADING_TOOLS.filter(
    (tool) =>
      tool.name.toLowerCase().includes(lowerQuery) ||
      tool.shortName.toLowerCase().includes(lowerQuery) ||
      tool.description.toLowerCase().includes(lowerQuery) ||
      tool.id.toLowerCase().includes(lowerQuery)
  );
}

export function getToolsForAIContext(): string {
  const categorized: Record<string, string[]> = {};
  
  for (const tool of TRADING_TOOLS) {
    const categoryName = TOOL_CATEGORIES[tool.category].name;
    if (!categorized[categoryName]) {
      categorized[categoryName] = [];
    }
    categorized[categoryName].push(`${tool.name} (${tool.shortName})`);
  }
  
  let context = "Available Trading Tools:\n\n";
  for (const [category, tools] of Object.entries(categorized)) {
    context += `${category}:\n${tools.join(", ")}\n\n`;
  }
  
  return context;
}

